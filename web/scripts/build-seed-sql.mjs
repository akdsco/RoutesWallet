/*
 * TB-110 — generate the D1 seed SQL that loads the baked-in club routes into the
 * shared pool, so a visitor sees a full library on first load (not an empty map)
 * and members contribute on top.
 *
 * Thin glue: the real work is the pure, unit-tested `buildSeedSql` in
 * src/lib/store.ts, imported directly (Node strips the TS types, same as
 * enrich-non-strava.mjs). Reads web/public/routes.geojson, writes
 * web/migrations/seed-routes.sql. Re-running with the same input rewrites it
 * identically — a re-runnable transform, not hand edits.
 *
 * RUN (from web/):  npm run build:seed-sql
 * DEPLOY:           wrangler d1 execute routeswallet --file=./migrations/0001_routes.sql
 *                   wrangler d1 execute routeswallet --file=./migrations/seed-routes.sql
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildSeedSql } from '../src/lib/store.ts';

const [major, minor] = process.versions.node.split('.').map(Number);
const stripsTypes =
  major > 23 || (major === 23 && minor >= 6) || (major === 22 && minor >= 18);
if (!stripsTypes) {
  console.error(
    `Needs Node >= 22.18 or >= 23.6 for TypeScript type-stripping; you have ${process.versions.node}.`
  );
  process.exit(1);
}

const here = dirname(fileURLToPath(import.meta.url));
const ROUTES_PATH = join(here, '..', 'public', 'routes.geojson');
const OUT_PATH = join(here, '..', 'migrations', 'seed-routes.sql');

const fc = JSON.parse(readFileSync(ROUTES_PATH, 'utf8'));
const features = Array.isArray(fc.features) ? fc.features : [];
const usable = features.filter(
  (f) =>
    f?.geometry?.type === 'LineString' && typeof f.properties?.id === 'string'
);

// D1 rejects a single SQL statement over ~100KB (SQLITE_TOOBIG), and a seed is
// transactional — one oversized INSERT aborts the whole load. A few routes carry
// huge full-resolution geometry (300KB+ as inline SQL), so skip those here and
// warn loudly rather than emit a seed that fails. The runtime insert path uses
// bound parameters and has no such limit; a fidelity-preserving seed for the fat
// routes is tracked separately (see the seed-size ticket).
const D1_MAX_STATEMENT = 100_000;
const statements = [];
const skipped = [];
for (const f of usable) {
  const stmt = buildSeedSql([f]).trimEnd();
  if (stmt.length > D1_MAX_STATEMENT) {
    skipped.push({
      id: f.properties.id,
      name:
        typeof f.properties.name === 'string'
          ? f.properties.name
          : f.properties.id,
      kb: Math.round(stmt.length / 1024),
    });
    continue;
  }
  statements.push(stmt);
}

const header =
  '-- GENERATED by scripts/build-seed-sql.mjs from public/routes.geojson. Do not hand-edit.\n';
writeFileSync(OUT_PATH, header + statements.join('\n') + '\n', 'utf8');

console.log(
  `Wrote ${statements.length} seed routes to migrations/seed-routes.sql` +
    (usable.length !== features.length
      ? ` (skipped ${features.length - usable.length} non-LineString/idless features)`
      : '')
);
if (skipped.length > 0) {
  console.warn(
    `\n⚠️  Skipped ${skipped.length} route(s) too large for a single D1 statement (>${D1_MAX_STATEMENT / 1000}KB) — these are absent from the seed until the fidelity-preserving fix lands (see seed-size ticket):`
  );
  for (const s of skipped) console.warn(`   - ${s.name} (${s.id}) ~${s.kb}KB`);
}
